def compact_set(elements, line_length=0):
    """Return the representation of a set with the given integer elements"""
    elements = sorted(elements)
    if not elements:
        return "set()"
    entries = []
    def add_range(first, last):
        r = range(first, last + 1)
        if len(r) <= 3:
            # 3 or fewer items are listed individually
            for e in r:
                entries.append(str(e))
        else:
            entries.append(f'*{r}')
    first = last = None
    for element in elements:
        if first is None:
            first = last = element
        elif element == last + 1:
            last += 1
        else:
            add_range(first, last)
            first = last = element
    add_range(first, last)
    return '{' + line_wrap_items(entries, line_length+1) + '}'

def line_wrap_items(items, line_length):
    result = ['']
    for item in items:
        if line_length + len(item) >= 79:
            result[-1] = result[-1].strip()
            result.append('\n    ')
            line_length = 4
        result.append(item + ', ')
        line_length += len(item) + 2
    result[-1] = result[-1].strip(', ')
    return ''.join(result)

############## Read the tables in the RFC #######################

with open("Tools/unicode/data/rfc3454.txt", encoding='utf-8') as data_file:
    data = data_file.readlines()

tables = []
table_titles = {}
curname = None
for l in data:
    l = l.strip()
    if not l:
        continue
    # Skip RFC page breaks
    if l.startswith(("Hoffman & Blanchet", "RFC 3454")):
        continue
    # Find appendix section titles
    m = re.fullmatch("([A-Z](.[0-9])+) (.*)", l)
    if m:
        table_titles[m[1].replace('.', '').lower()] = m[0]
    # Find start/end lines
    m = re.fullmatch("----- (Start|End) Table ([A-Z](.[0-9])+) -----", l)
    if m:
        if m.group(1) == "Start":
            if curname:
                raise RuntimeError("Double Start", (curname, l))
            curname = m.group(2)
            table = {}
            tables.append((curname, table))
            continue
        else:
            if not curname:
                raise RuntimeError("End without start", l)
            if curname != m.group(2):
                raise RuntimeError("Unexpected end", l)
            curname = None
            continue
    if not curname:
        continue
    # Now we are in a table
    fields = l.split(";")
    if len(fields) > 1:
        # Drop comment field
        fields = fields[:-1]
    if len(fields) == 1:
        fields = fields[0].split("-")
        if len(fields) > 1:
            # range
            try:
                start, end = fields
            except ValueError:
                raise RuntimeError("Unpacking problem", l)
        else:
            start = end = fields[0]
        start = int(start, 16)
        end = int(end, 16)
        for i in range(start, end+1):
            table[i] = i
    else:
        code, value = fields
        value = value.strip()
        if value:
            value = [int(v, 16) for v in value.split(" ")]
        else:
            # table B.1
            value = None
        table[int(code, 16)] = value

# Keep a copy for later
orig_tables = list(tables)

# Make pop() start with the first one
tables.reverse()

def pop_table(expected_name):
    """Pop the next table and assert it has the given name"""
    name, table = tables.pop()
    assert name == expected_name
    return table

########### Helpers for printing out Python functions #############

results = []
def output(*strings, end='\n'):
    content = ' '.join(strings) + end
    print(content, end='')
    results.append(content)

def output_in_table_head(name):
    output(f'def in_table_{name}(code):')
    if title := table_titles.get(name):
        output(f'    {"Lookup in RFC 3454 " + title!r}')

def output_in_table_function(name, table, code=None, **ns):
    print(f'Generating table {name}', file=sys.stderr)
    output()
    if code is not None:
        output_in_table_head(name)
        output(code.strip('\n'))
    else:
        lower = min(table)
        upper = max(table) + 1
        if len(table) == upper - lower:
            assert set(table) == set(range(lower, upper))
            output_in_table_head(name)
            output(f'    return ord(code) in range({lower:#x}, {upper:#x})')
        else:
            output(f'_{name}_set = frozenset({compact_set(table, 20)})')
            output_in_table_head(name)
            output(f'    return ord(code) in _{name}_set')
    output()

