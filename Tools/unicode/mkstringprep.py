# B.2 and B.3 is case folding.
# It takes CaseFolding.txt into account, which is
# not available in the Python database. Since
# B.2 is derived from B.3, we process B.3 first.
# B.3 supposedly *is* CaseFolding-3.2.0.txt.

table_b2 = pop_table("B.2")
table_b3 = pop_table("B.3")

# B.3 is mostly Python's .lower, except for a number
# of special cases, e.g. considering canonical forms.
# To enforce Unicode 3.2.0 behavior of .lower instead of
# whatever Unicode version is included with Python we
# add unassigned or newly case-folding codepoints to
# the exception map, too.

b3_exceptions = {}
b3_identities = []

for k,v in table_b3.items():
    if list(map(ord, chr(k).lower())) != v:
        b3_exceptions[k] = "".join(map(chr,v))
for cp in range(0x110000):
    ch = chr(cp)
    # Assigned in current Unicode version
    # and supports case folding, but not
    # explicitly in B.2 or B.3 tables.
    if (unicodedata_current.category(ch) != "Cn"
            and ch.lower() != ch
            and cp not in table_b2
            and cp not in table_b3):
        b3_identities.append(cp)

b3 = sorted(b3_exceptions.items())

output("""
b3_exceptions = frozendict({
    """ + line_wrap_items((f"{k:#x}:{v!a}" for k, v in b3), 4) + """,
    **{cp: chr(cp) for cp in """ + compact_set(b3_identities, 32) + """}
})
""")

output("""
def map_table_b3(code):
    r = b3_exceptions.get(ord(code))
    if r is not None: return r
    return code.lower()
""")

def map_table_b3(code):
    r = b3_exceptions.get(ord(code))
    if r is not None: return r
    return code.lower()

# B.2 is case folding for NFKC. This is the same as B.3,
# except where NormalizeWithKC(Fold(a)) !=
# NormalizeWithKC(Fold(NormalizeWithKC(Fold(a))))

def map_table_b2(a):
    al = map_table_b3(a)
    b = unicodedata_320.normalize("NFKC", al)
    bl = "".join([map_table_b3(ch) for ch in b])
    c = unicodedata_320.normalize("NFKC", bl)
    if b != c:
        return c
    else:
        return al

specials = {}
for k,v in table_b2.items():
    if list(map(ord, map_table_b2(chr(k)))) != v:
        specials[k] = v

# B.3 should not add any additional special cases
assert specials == {}

