#!/usr/bin/python
"""Generate type/module slot files.
"""

import io
import csv
import sys
import json
import tomllib
import argparse
import functools
import contextlib
import dataclasses
from pathlib import Path

GENERATED_BY = 'Generated by Tools/build/generate_slots.py'

REPO_ROOT = Path(__file__).parent.parent.parent
DEFAULT_INPUT_PATH = REPO_ROOT / 'Python/slots.toml'
DEFAULT_HEADER_PATH = REPO_ROOT / 'Include/slots_generated.h'
DEFAULT_C_PATH = REPO_ROOT / 'Python/slots_generated.c'

TYPE_TABLES = {
    'tp': ('PyTypeObject', None, None),
    'mp': ('PyTypeObject', 'tp_as_mapping', 'PyMappingMethods'),
    'nb': ('PyTypeObject', 'tp_as_number', 'PyNumberMethods'),
    'sq': ('PyTypeObject', 'tp_as_sequence', 'PySequenceMethods'),
    'am': ('PyTypeObject', 'tp_as_async', 'PyAsyncMethods'),
    'bf': ('PyTypeObject', 'tp_as_buffer', 'PyBufferProcs'),
    'ht': ('PyHeapTypeObject', None, None),
}


@dataclasses.dataclass
class SlotInfo:
    name: str
    id: int
    kind: str

    def generate_c_initializers(self):
        assert self.name.isidentifier() and self.name.isascii()
        yield "name", f'"{self.name}"'
        yield "dtype", f'_PySlot_TYPE_{self.data_type.upper()}'
        yield "kind", f'_PySlot_KIND_{self.kind.upper()}'


@dataclasses.dataclass
class DataSlot(SlotInfo):
    data_type: str
    duplicates: str | None = None
    null: str = 'deprecated'
    subslots: bool = False
    is_name: bool = False
    compat_id: int | None = None

    def generate_c_initializers(self):
        yield from super().generate_c_initializers()
        if self.subslots:
            yield 'is_subslots', 'true'
        match self.null:
            case 'reject':
                yield 'null_handling', '_PySlot_NULL_REJECT'
            case 'allow':
                yield 'null_handling', '_PySlot_NULL_ALLOW'
            case _:
                if self.data_type in {'func', 'ptr'}:
                    if self.id > 92:
                        raise ValueError(
                            f'slot {self.name} needs explicit NULL '
                            + 'handling specification')
                    yield 'null_handling', '_PySlot_NULL_DEPRECATED'
                else:
                    yield 'null_handling', '_PySlot_NULL_ALLOW'
        match self.duplicates:
            case 'reject':
                yield 'reject_duplicates', 'true'
            case 'allow':
                pass
            case _:
                yield 'deprecate_duplicates', 'true'
        if self.is_name:
            yield 'is_name', 'true'


@dataclasses.dataclass
class MetaSlot(DataSlot):
    pass


@dataclasses.dataclass
class TypeSlot(DataSlot):
    table: str = dataclasses.field(kw_only=True)
    field: str = dataclasses.field(kw_only=True)

    def generate_c_initializers(self):
        yield from super().generate_c_initializers()
        if self.table:
            typeobj, subtable, tabletype = TYPE_TABLES[self.table]
            if subtable:
                yield (
                    'type_info.slot_offset',
                    f'offsetof({typeobj}, {subtable})',
                )
                yield (
                    'type_info.subslot_offset',
                    f'offsetof({tabletype}, {self.field})',
                )
            else:
                yield (
                    'type_info.slot_offset',
                    f'offsetof({typeobj}, {self.field})',
                )
                yield 'type_info.subslot_offset', '-1'


@dataclasses.dataclass
class ModSlot(DataSlot):
    pass


@dataclasses.dataclass
class CompatSlot(SlotInfo):
    new_slot_names: dict

    data_type = 'void'

    def generate_c_initializers(self):
        yield from super().generate_c_initializers()
        for kind, new_id in self.new_slot_ids.items():
            yield f'compat_info.{kind}_id', new_id


def make_slot_info(name, info_dict):
    if 'kind' not in info_dict:
        if name.startswith('slot_'):
            info_dict['kind'] = 'slot'
        elif name.startswith('mod_'):
            info_dict['kind'] = 'mod'
        else:
            for table in TYPE_TABLES:
                if name.startswith(table + '_'):
                    info_dict['kind'] = 'type'
                    info_dict.setdefault('table', table)
                    info_dict.setdefault('field', name)
    cls = {
        'type': TypeSlot,
        'mod': ModSlot,
        'slot': MetaSlot,
        'compat': CompatSlot,
    }[info_dict['kind']]
    return cls(name, **info_dict)


def parse_slots(file):
    slots_by_number = {}
    slots_by_name = {}
    for name, entry in tomllib.load(file).items():
        slot = make_slot_info(name, entry)
        if prev := slots_by_number.get(slot.id):
            raise ValueError(
                f'duplicate slot ID: {slot.id} ({prev.name} and {slot.name})')
        slots_by_number[slot.id] = slot
        if prev := slots_by_name.get(slot.name):
            raise ValueError(
                f'duplicate slot name: {slot.name} ({prev.id} and {slot.id})')
        slots_by_name[slot.name] = slot

    # Now that we have all the slots, add "new_slot_ids" to compat slots
    for slot in slots_by_number.values():
        if slot.kind == 'compat':
            slot.new_slot_ids = {}
            for kind, new_name in slot.new_slot_names.items():
                new_slot = slots_by_name[new_name]
                new_slot.compat_id = slot.id
                slot.new_slot_ids[kind] = new_slot.id

    # Reduce to a single list
    max_id = max(slots_by_number)
    return [slots_by_number[i] for i in range(max_id+1)]


def write_header(f, slots):
    out = functools.partial(print, file=f)
    out(f'/* {GENERATED_BY} */')
    out()
    out(f'#ifndef _PY_HAVE_SLOTS_GENERATED_H')
    out(f'#define _PY_HAVE_SLOTS_GENERATED_H')
    out()
    out(f'#if !defined(Py_LIMITED_API) || Py_LIMITED_API+0 >= _Py_PACK_VERSION(3, 15)')
    out(f'#define _Py_SLOT_COMPAT_VALUE(OLD, NEW) NEW')
    out(f'#else')
    out(f'#define _Py_SLOT_COMPAT_VALUE(OLD, NEW) OLD')
    out(f'#endif')
    out()
    for slot in slots:
        if slot.kind == 'compat':
            continue
        if slot.kind == 'mod':
            # XXX: Skip module slots for now
            continue
        slot_id = slot.id
        if slot.compat_id is not None:
            slot_id = f'_Py_SLOT_COMPAT_VALUE({slot.compat_id}, {slot.id})'
            # XXX: Use old slot IDs for now
            slot_id = slot.compat_id
        out(f'#define Py_{slot.name} {slot_id}')
    out()
    out(f'#define _Py_slot_COUNT {len(slots)}')
    out(f'#endif')


def write_c(f, slots):
    out = functools.partial(print, file=f)
    out(f'/* {GENERATED_BY} */')
    out()
    out('#include "Python.h"')
    out('#include "pycore_slots.h"   // _PySlot_Info')
    out('#include <stddef.h>         // offsetof')
    out('#include <stdbool.h>        // true')
    out()
    out(f'_PySlot_Info _PySlot_InfoTable[_Py_slot_COUNT + 1] = {{')

    assert len(slots) == max(slot.id for slot in slots) + 1
    for slot in slots:
        try:
            out(f"    [{slot.id}] = {{")
            for name, initializer in slot.generate_c_initializers():
                out(f'        .{name} = {initializer},')
            out(f"    }},")
        except Exception as e:
            e.add_note(f'handling slot {slot}')
            raise e
    out(f"    [{len(slots)}] = {{0}}")
    out(f"}};")


@contextlib.contextmanager
def replace_file(filename):
    file_path = Path(filename)
    with io.StringIO() as sio:
        yield sio
        try:
            old_text = file_path.read_text()
        except FileNotFoundError:
            old_text = None
        new_text = sio.getvalue()
        if old_text == new_text:
            print(f'{filename}: not modified', file=sys.stderr)
        else:
            print(f'{filename}: writing new content', file=sys.stderr)
            file_path.write_text(new_text)


def main(argv):
    if len(argv) == 1:
        # No sens calling this with no arguments.
        argv.append('--help')

    parser = argparse.ArgumentParser(prog=argv[0], description=__doc__)
    parser.add_argument(
        '-i', '--input', default=DEFAULT_INPUT_PATH,
        help=f'the input file (default: {DEFAULT_INPUT_PATH})')
    parser.add_argument(
        '--generate-all', action=argparse.BooleanOptionalAction,
        help='write all output files to their default locations')
    parser.add_argument(
        '-j', '--json', action=argparse.BooleanOptionalAction,
        help='write info to stdout in JSON format')
    outfile_group = parser.add_argument_group(
        'output files',
        description='By default, no files are generated. Use --generate-all '
            + 'or the options below to generate them.')
    outfile_group.add_argument(
        '-H', '--header',
        help='file into which to write the public header')
    outfile_group.add_argument(
        '-C', '--cfile',
        help='file into which to write internal C code')
    args = parser.parse_args(argv[1:])

    if args.generate_all:
        if args.header is None:
            args.header = DEFAULT_HEADER_PATH
        if args.cfile is None:
            args.cfile = DEFAULT_C_PATH

    with open(args.input, 'rb') as f:
        slots = parse_slots(f)

    if args.json:
        print('[')
        for slot in slots[:-1]:
            print('   ', json.dumps(dataclasses.asdict(slot)) + ',')
        print('   ', json.dumps(dataclasses.asdict(slots[-1])))
        print(']')

    if args.header:
        with replace_file(args.header) as f:
            write_header(f, slots)

    if args.cfile:
        with replace_file(args.cfile) as f:
            write_c(f, slots)

if __name__ == "__main__":
    main(sys.argv)
