#!/usr/bin/python
"""Generate type slot files.

Usage: typeslots.py -i slots.csv slots.inc Include/slots.h
"""

import io
import csv
import sys
import json
import argparse
import functools
import contextlib
from pathlib import Path

GENERATED_BY = 'Generated by Objects/typeslots.py'

class SlotInfo:
    def __init__(self, **info_dict):
        self._d = info_dict
        self.id = int(self['id'])
        assert self.id >= 0
        self.name = self['name']
        self.kind = self['kind']
        self.dtype = self['dtype']

    def to_dict(self):
        return self._d

    def __getitem__(self, name):
        return self._d[name]

    def get(self, name, default=None):
        return self._d.get(name, default)

    def get_int(self, name, default=None):
        try:
            return int(self._d[name])
        except KeyError:
            return default

    @functools.cached_property
    def added(self):
        added = self._d.get('added')
        if added is None:
            return None
        x, y = added.split('.')
        return int(x), int(y)

    @functools.cached_property
    def type_table(self):
        try:
            return self['table']
        except KeyError:
            return self.name.partition('_')[0]


def parse_slots(lines):
    result = []
    reader = csv.DictReader(lines, restkey='named', skipinitialspace=True)
    for info_dict in reader:
        if info_dict.get('id', '#') == '#':
            continue
        for kv in info_dict.pop('named', ()):
            key, eq, value = kv.partition('=')
            info_dict[key] = value
        result.append(SlotInfo(**info_dict))
    return result


def write_header(f, slots):
    out = functools.partial(print, file=f)
    out(f'/* {GENERATED_BY} */')
    out()
    out(f'#if !defined(Py_LIMITED_API) || Py_LIMITED_API+0 >= Py_PACK_VERSION(3, 14)')
    out(f'#define _Py_SLOT_COMPAT_VALUE(OLD, NEW) NEW')
    out(f'#else')
    out(f'#define _Py_SLOT_COMPAT_VALUE(OLD, NEW) OLD')
    out(f'#endif')
    out()
    for slot in slots:
        if slot.kind == 'compat':
            continue
        slot_id = slot.id
        if compat := slot.get('compat'):
            slot_id = f'_Py_SLOT_COMPAT_VALUE({compat}, {slot.id})'
        out(f'#define Py_{slot.name} {slot_id}')


def write_inc(f, slots):
    out = functools.partial(print, file=f)
    out(f'/* {GENERATED_BY} */')
    out()
    assert len(slots) == max(slot.id for slot in slots) + 1
    out(f'_PySlot_Info _PySlot_InfoTable[] = {{')
    for slot in slots:
        out(f"    [{slot.id}] = {{")
        initializers = {
            "name": f'"{slot.name}"',
            "dtype": f'_PySlot_TYPE_{slot.dtype.upper()}',
            "kind": f'_PySlot_KIND_{slot.kind.upper()}',
        }
        if not slot.get_int('virtual'):
            match slot.kind:
                case 'any':
                    pass
                case 'compat':
                    for newslot in slots:
                        if newslot.get_int('compat') == slot.id:
                            key = f'compat_info.{newslot.kind}_id'
                            initializers[key] = newslot.id
                case 'type':
                    tpo = 'PyTypeObject'
                    typeobj, subtable = {
                        'tp': (tpo, None),
                        'mp': (tpo, 'PyMappingMethods'),
                        'nb': (tpo, 'PyNumberMethods'),
                        'sq': (tpo, 'PySequenceMethods'),
                        'am': (tpo, 'PyAsyncMethods'),
                        'bf': (tpo, 'PyBufferProcs'),
                        'ht': ('PyHeapTypeObject', None),
                    }[slot.type_table]
                    if subtable:
                        initializers['type_info.subslot_offset'] = (
                            f'offsetof({subtable}, {slot.name})')
                        initializers['type_info.slot_offset'] = (
                            f'offsetof({typeobj}, {subtable})')
                    else:
                        initializers['type_info.subslot_offset'] = '-1'
                        initializers['type_info.slot_offset'] = (
                            f'offsetof({typeobj}, {slot.name})')
                case 'mod':
                    pass
                case _:
                    raise ValueError(slot.kind)
        for name, initializer in initializers.items():
            out(f'        .{name}={initializer},')
        out(f"    }},")
    out(f"    [{len(slots)}] = {{0}}")
    out(f"}};")



@contextlib.contextmanager
def replace_file(filename):
    file_path = Path(filename)
    with io.StringIO() as sio:
        yield sio
        try:
            old_text = file_path.read_text()
        except FileNotFoundError:
            old_text = None
        new_text = sio.getvalue()
        if old_text == new_text:
            print(f'{filename}: not modified', file=sys.stderr)
        else:
            print(f'{filename}: writing new content', file=sys.stderr)
            file_path.write_text(new_text)


def main(argv):
    HERE = Path(__file__).parent
    parser = argparse.ArgumentParser(prog=argv[0], description=__doc__)
    parser.add_argument(
        '-i', '--input', default=Path(HERE/'slots.csv'),
        help='The input file.')
    parser.add_argument(
        '-w', '--write', action=argparse.BooleanOptionalAction,
        help='Write output files to their default locations')
    parser.add_argument(
        '-j', '--jsonl', action=argparse.BooleanOptionalAction,
        help='Write info to stdout in JSON Lines format (one JSON per line)')
    parser.add_argument(
        '-H', '--header',
        help='File into which to write the public header')
    parser.add_argument(
        '-I', '--incfile',
        help='File into which to write internal C code')
    args = parser.parse_args(argv[1:])

    if args.write:
        if args.header is None:
            args.header = HERE.parent / 'Include/slots.h'
        if args.incfile is None:
            args.incfile = HERE / 'slots.inc'

    with open(args.input) as f:
        slots = parse_slots(f)

    if args.jsonl:
        for slot in slots:
            print(json.dumps(slot.to_dict()))

    if args.header:
        with replace_file(args.header) as f:
            write_header(f, slots)

    if args.incfile:
        with replace_file(args.incfile) as f:
            write_inc(f, slots)

if __name__ == "__main__":
    main(sys.argv)
